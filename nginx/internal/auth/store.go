const (
	pbkdf2Iterations = 210000
	pbkdf2KeyLen     = 32
	saltLenBytes     = 16
)

var usernameRegex = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._-]{2,31}$`)

type persistedAuth struct {
	Username     string `json:"username"`
	PasswordHash string `json:"password_hash"`
	AuthToken    string `json:"auth_token,omitempty"`
	UpdatedAt    string `json:"updated_at"`
}

// AccountInfo 对外返回的非敏感管理员账户信息
type AccountInfo struct {
	Username    string `json:"username"`
	Source      string `json:"source"` // "persisted" 或 "env"
	UpdatedAt   string `json:"updated_at"`
	AuthFile    string `json:"auth_file"`
	TokenPinned bool   `json:"token_pinned"`
}

// Store 线程安全的管理员凭证与会话令牌存储（纯标准库 PBKDF2-HMAC-SHA256，零外部依赖）
type Store struct {
	mu           sync.RWMutex
	authFile     string
	username     string
	passwordHash string
	authToken    string
	tokenPinned  bool
	source       string
	updatedAt    string
}

// NewStore 初始化凭证仓库：优先读取 /data/.auth.json，若不存在或开启 RESET_ADMIN_AUTH=true 则从环境变量初始化
func NewStore(authFile, envUser, envPass, envToken string, tokenAutoGenerated, resetFromEnv bool) *Store {
	s := &Store{
		authFile:    filepath.Clean(authFile),
		username:    strings.TrimSpace(envUser),
		authToken:   envToken,
		tokenPinned: !tokenAutoGenerated,
		source:      "env",
		updatedAt:   time.Now().UTC().Format(time.RFC3339),
	}
	if s.username == "" {
		s.username = "admin"
	}

	if !resetFromEnv {
		if loaded, err := s.loadFromDisk(); err == nil && loaded {
			return s
		}
	}

	hash, err := HashPassword(envPass)
	if err != nil {
		log.Fatalf("[FATAL] 无法计算初始管理员密码哈希: %v", err)
	}
	s.passwordHash = hash

	if resetFromEnv {
		if err := s.persistLocked(); err != nil {
			log.Printf("[WARN] RESET_ADMIN_AUTH 重置写入失败: %v", err)
		} else {
			s.source = "persisted"
			log.Printf("[SECURITY] 已根据环境变量重置管理员账号与密码并持久化至 %s", s.authFile)
		}
	}

	return s
}

func (s *Store) loadFromDisk() (bool, error) {
	raw, err := os.ReadFile(s.authFile)
	if err != nil {
		return false, err
	}
	var rec persistedAuth
	if err := json.Unmarshal(raw, &rec); err != nil {
		log.Printf("[WARN] 解析持久化凭证文件失败 (%s)，将回退至环境变量: %v", s.authFile, err)
		return false, err
	}
	if strings.TrimSpace(rec.Username) == "" || !strings.HasPrefix(rec.PasswordHash, "pbkdf2_sha256$") {
		return false, errors.New("invalid persisted auth format")
	}

	s.username = strings.TrimSpace(rec.Username)
	s.passwordHash = rec.PasswordHash
	if !s.tokenPinned && strings.TrimSpace(rec.AuthToken) != "" {
		s.authToken = strings.TrimSpace(rec.AuthToken)
	}
	s.source = "persisted"
	if rec.UpdatedAt != "" {
		s.updatedAt = rec.UpdatedAt
	}
	log.Printf("[INFO] 已加载持久化管理员凭证 (%s, 用户: %s)", s.authFile, s.username)
	return true, nil
}

// CurrentToken 返回当前生效的会话签名 Token（支持动态轮换）
func (s *Store) CurrentToken() string {
	s.mu.RLock()
	defer s.mu.RUnlock()
	return s.authToken
}

// VerifyToken 常量时间校验 API Token
func (s *Store) VerifyToken(candidate string) (bool, string) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	if candidate == "" || s.authToken == "" {
		return false, ""
	}
	if subtle.ConstantTimeCompare([]byte(candidate), []byte(s.authToken)) == 1 {
		return true, s.username
	}
	return false, ""
}

// VerifyCredentials 常量时间校验用户名与 PBKDF2-HMAC-SHA256 密码哈希（防用户名枚举时序泄露）
func (s *Store) VerifyCredentials(username, password string) (bool, string, string) {
	s.mu.RLock()
	expectedUser := s.username
	expectedHash := s.passwordHash
	token := s.authToken
	s.mu.RUnlock()

	userMatch := subtle.ConstantTimeCompare([]byte(strings.TrimSpace(username)), []byte(expectedUser)) == 1
	// 无论用户名是否匹配，始终执行一次完整 PBKDF2 校验以消除时序差异
	passMatch := VerifyPassword(password, expectedHash)
	if userMatch && passMatch {
		return true, expectedUser, token
	}
	return false, "", ""
}

// Info 返回当前非敏感账户信息
func (s *Store) Info() AccountInfo {
	s.mu.RLock()
	defer s.mu.RUnlock()
	return AccountInfo{
		Username:    s.username,
		Source:      s.source,
		UpdatedAt:   s.updatedAt,
		AuthFile:    s.authFile,
		TokenPinned: s.tokenPinned,
	}
}

// UpdateCredentials 校验当前密码并原子更新用户名/密码（可选轮换会话 Token），持久化至 /data/.auth.json (0600)
func (s *Store) UpdateCredentials(currentPassword, newUsername, newPassword string, rotateToken bool) (AccountInfo, string, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	if !VerifyPassword(currentPassword, s.passwordHash) {
		return AccountInfo{}, "", errors.New("当前密码校验失败")
	}

	targetUser := strings.TrimSpace(newUsername)
	if targetUser == "" {
		targetUser = s.username
	}
	if err := ValidateUsername(targetUser); err != nil {
		return AccountInfo{}, "", err
	}

	targetHash := s.passwordHash
	if newPassword != "" {
		if err := ValidatePasswordStrength(newPassword); err != nil {
			return AccountInfo{}, "", err
		}
		h, err := HashPassword(newPassword)
		if err != nil {
			return AccountInfo{}, "", fmt.Errorf("密码加密失败: %w", err)
		}
		targetHash = h
	} else if targetUser == s.username && !rotateToken {
		return AccountInfo{}, "", errors.New("未检测到用户名、密码或令牌变更")
	}

	nextToken := s.authToken
	if rotateToken || newPassword != "" || targetUser != s.username {
		if !s.tokenPinned {
			tok, err := randomHexBytes(32)
			if err != nil {
				return AccountInfo{}, "", fmt.Errorf("无法轮换会话令牌: %w", err)
			}
			nextToken = tok
		}
	}

	prevUser, prevHash, prevToken, prevSource, prevUpdated := s.username, s.passwordHash, s.authToken, s.source, s.updatedAt
	s.username = targetUser
	s.passwordHash = targetHash
	s.authToken = nextToken
	s.source = "persisted"
	s.updatedAt = time.Now().UTC().Format(time.RFC3339)

	if err := s.persistLocked(); err != nil {
		s.username, s.passwordHash, s.authToken, s.source, s.updatedAt = prevUser, prevHash, prevToken, prevSource, prevUpdated
		return AccountInfo{}, "", fmt.Errorf("持久化凭证失败: %w", err)
	}

	return AccountInfo{
		Username:    s.username,
		Source:      s.source,
		UpdatedAt:   s.updatedAt,
		AuthFile:    s.authFile,
		TokenPinned: s.tokenPinned,
	}, s.authToken, nil
}

func (s *Store) persistLocked() error {
	dir := filepath.Dir(s.authFile)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	rec := persistedAuth{
		Username:     s.username,
		PasswordHash: s.passwordHash,
		UpdatedAt:    s.updatedAt,
	}
	if !s.tokenPinned {
		rec.AuthToken = s.authToken
	}
	data, err := json.MarshalIndent(rec, "", "  ")
	if err != nil {
		return err
	}

	tmp, err := os.CreateTemp(dir, ".auth-tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	cleanup := true
	defer func() {
		if cleanup {
			_ = os.Remove(tmpName)
		}
	}()

	if err := tmp.Chmod(0600); err != nil {
		_ = tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, s.authFile); err != nil {
		return err
	}
	cleanup = false
	return nil
}

// ValidateUsername 校验管理员用户名格式（3-32 位字母数字及 . _ -）
func ValidateUsername(u string) error {
	if !usernameRegex.MatchString(u) {
		return errors.New("用户名需为 3~32 位，仅支持字母、数字、点(.)、下划线(_)和连字符(-)，且需以字母或数字开头")
	}
	return nil
}

// ValidatePasswordStrength 强密码策略：至少 8 位且包含大写、小写、数字（或 >=12 位含至少两类字符），禁止控制字符
func ValidatePasswordStrength(p string) error {
	if len(p) < 8 || len(p) > 128 {
		return errors.New("新密码长度需为 8~128 位")
	}
	var hasUpper, hasLower, hasDigit, hasSymbol bool
	for _, r := range p {
		if r < 0x20 || r == 0x7f {
			return errors.New("密码不能包含控制字符")
		}
		switch {
		case unicode.IsUpper(r):
			hasUpper = true
		case unicode.IsLower(r):
			hasLower = true
		case unicode.IsDigit(r):
			hasDigit = true
		default:
			hasSymbol = true
		}
	}
	classes := 0
	if hasUpper {
		classes++
	}
	if hasLower {
		classes++
	}
	if hasDigit {
		classes++
	}
	if hasSymbol {
		classes++
	}
	if len(p) < 12 && !(hasUpper && hasLower && hasDigit) {
		return errors.New("密码强度不足：12 位以下需同时包含大写字母、小写字母和数字")
	}
	if classes < 2 {
		return errors.New("密码强度不足：请至少混合两类字符（字母/数字/符号）")
	}
	return nil
}

// HashPassword 使用 PBKDF2-HMAC-SHA256 生成随机盐密码哈希
func HashPassword(password string) (string, error) {
	salt := make([]byte, saltLenBytes)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	dk := pbkdf2HMACSHA256([]byte(password), salt, pbkdf2Iterations, pbkdf2KeyLen)
	return fmt.Sprintf("pbkdf2_sha256$%d$%s$%s", pbkdf2Iterations, hex.EncodeToString(salt), hex.EncodeToString(dk)), nil
}

// VerifyPassword 常量时间验证 PBKDF2-HMAC-SHA256 哈希
func VerifyPassword(password, encoded string) bool {
	parts := strings.Split(encoded, "$")
	if len(parts) != 4 || parts[0] != "pbkdf2_sha256" {
		return false
	}
	iter, err := strconv.Atoi(parts[1])
	if err != nil || iter < 10000 || iter > 2000000 {
		return false
	}
	salt, err := hex.DecodeString(parts[2])
	if err != nil || len(salt) == 0 {
		return false
	}
	expected, err := hex.DecodeString(parts[3])
	if err != nil || len(expected) == 0 {
		return false
	}
	actual := pbkdf2HMACSHA256([]byte(password), salt, iter, len(expected))
	return subtle.ConstantTimeCompare(actual, expected) == 1
}

// pbkdf2HMACSHA256 RFC 2898 / RFC 8018 标准纯 Go 实现（零外部依赖）
func pbkdf2HMACSHA256(password, salt []byte, iter, keyLen int) []byte {
	hashLen := sha256.Size
	numBlocks := (keyLen + hashLen - 1) / hashLen
	dk := make([]byte, 0, numBlocks*hashLen)

	buf := make([]byte, len(salt)+4)
	copy(buf, salt)

	for block := 1; block <= numBlocks; block++ {
		buf[len(salt)] = byte(block >> 24)
		buf[len(salt)+1] = byte(block >> 16)
		buf[len(salt)+2] = byte(block >> 8)
		buf[len(salt)+3] = byte(block)

		mac := hmac.New(sha256.New, password)
		mac.Write(buf)
		u := mac.Sum(nil)
		t := make([]byte, len(u))
		copy(t, u)

		for i := 1; i < iter; i++ {
			mac.Reset()
			mac.Write(u)
			u = mac.Sum(u[:0])
			for j := range t {
				t[j] ^= u[j]
			}
		}
		dk = append(dk, t...)
	}
	return dk[:keyLen]
}

func randomHexBytes(n int) (string, error) {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}
