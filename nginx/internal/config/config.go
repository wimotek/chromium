package config

import (
	"crypto/rand"
	"encoding/hex"
	"log"
	"os"
	"path/filepath"
	"strconv"
	"time"
)

type Config struct {
	AdminUser          string
	AdminPass          string
	AuthToken          string
	TokenAutoGenerated bool
	PassAutoGenerated  bool
	DataDir            string
	NginxBin           string
	NginxDir           string
	NginxMainConf      string
	DefaultMainConf    string
	SSLDir             string
	AcmeScriptHome     string
	AcmeHome           string
	AcmeWebRoot        string
	LogDir             string
	AuthFile           string
	TrustProxy         bool
	ResetAdminAuth     bool
	MCPEnabled         bool
	MCPReadOnly        bool
	MCPToken           string
	MCPFile            string
	HttpPort           string
	AutoRenewInterval  time.Duration
}

func Load() *Config {
	adminPass := os.Getenv("ADMIN_PASS")
	passGenerated := false
	if adminPass == "" {
		adminPass = randomHex(12)
		passGenerated = true
	}

	authToken := os.Getenv("AUTH_TOKEN")
	tokenGenerated := false
	if authToken == "" {
		authToken = randomHex(32)
		tokenGenerated = true
	}

	renewHours := 12
	if raw := os.Getenv("ACME_RENEW_HOURS"); raw != "" {
		if parsed, err := strconv.Atoi(raw); err == nil && parsed >= 1 {
			renewHours = parsed
		}
	}

	dataDir := filepath.Clean(getEnv("DATA_DIR", "/data"))

	cfg := &Config{
		AdminUser:          getEnv("ADMIN_USER", "admin"),
		AdminPass:          adminPass,
		AuthToken:          authToken,
		TokenAutoGenerated: tokenGenerated,
		PassAutoGenerated:  passGenerated,
		DataDir:            dataDir,
		NginxBin:           getEnv("NGINX_BIN", "nginx"),
		NginxDir:           getEnv("NGINX_DIR", filepath.Join(dataDir, "conf.d")),
		NginxMainConf:      getEnv("NGINX_MAIN_CONF", filepath.Join(dataDir, "nginx.conf")),
		DefaultMainConf:    getEnv("NGINX_DEFAULT_CONF", "/etc/nginx/nginx.conf.default"),
		SSLDir:             getEnv("SSL_DIR", filepath.Join(dataDir, "ssl")),
		AcmeScriptHome:     getEnv("ACME_SCRIPT_HOME", "/opt/acme.sh"),
		AcmeHome:           getEnv("ACME_HOME", filepath.Join(dataDir, "acme")),
		AcmeWebRoot:        getEnv("ACME_WEBROOT", filepath.Join(dataDir, "www", "acme")),
		LogDir:             getEnv("LOG_DIR", filepath.Join(dataDir, "logs")),
		AuthFile:           getEnv("AUTH_FILE", filepath.Join(dataDir, ".auth.json")),
		TrustProxy:         os.Getenv("TRUST_PROXY") == "true",
		ResetAdminAuth:     os.Getenv("RESET_ADMIN_AUTH") == "true",
		MCPEnabled:         os.Getenv("MCP_ENABLED") == "true",
		MCPReadOnly:        os.Getenv("MCP_READ_ONLY") == "true",
		MCPToken:           os.Getenv("MCP_TOKEN"),
		MCPFile:            getEnv("MCP_FILE", filepath.Join(dataDir, ".mcp.json")),
		HttpPort:           getEnv("HTTP_PORT", ":8080"),
		AutoRenewInterval:  time.Duration(renewHours) * time.Hour,
	}

	if passGenerated {
		log.Printf("[SECURITY] ADMIN_PASS 未配置，本次启动已生成随机管理员密码: %s (建议在环境变量中显式设置)", cfg.AdminPass)
	}
	if tokenGenerated {
		log.Printf("[SECURITY] AUTH_TOKEN 未配置，本次启动已生成随机会话签名密钥")
	}

	return cfg
}

// BootstrapDataDir 首次挂载空 /data 目录时自动初始化子目录与默认 nginx.conf
func BootstrapDataDir(cfg *Config) {
	dirs := []string{
		cfg.DataDir,
		cfg.NginxDir,
		cfg.SSLDir,
		cfg.AcmeHome,
		filepath.Join(cfg.DataDir, "www"),
		cfg.AcmeWebRoot,
		cfg.LogDir,
	}
	for _, d := range dirs {
		if err := os.MkdirAll(d, 0755); err != nil {
			log.Printf("[WARN] 初始化数据目录失败 (%s): %v", d, err)
		}
	}

	if _, err := os.Stat(cfg.NginxMainConf); os.IsNotExist(err) {
		if raw, readErr := os.ReadFile(cfg.DefaultMainConf); readErr == nil {
			if writeErr := os.WriteFile(cfg.NginxMainConf, raw, 0644); writeErr != nil {
				log.Printf("[WARN] 写入默认主配置失败 (%s): %v", cfg.NginxMainConf, writeErr)
			} else {
				log.Printf("[INFO] 检测到空数据卷，已自动初始化默认主配置: %s", cfg.NginxMainConf)
			}
		} else {
			log.Printf("[WARN] 未找到内置默认配置模板 (%s): %v", cfg.DefaultMainConf, readErr)
		}
	}
}

func getEnv(k, def string) string {
	if v := os.Getenv(k); v != "" {
		return v
	}
	return def
}

func randomHex(numBytes int) string {
	b := make([]byte, numBytes)
	if _, err := rand.Read(b); err != nil {
		log.Fatalf("[FATAL] 无法生成安全随机密钥: %v", err)
	}
	return hex.EncodeToString(b)
}